-- Portable SQL: runs on PostgreSQL (prod, docker, CI) and H2 in PostgreSQL mode (local, no Docker).

CREATE TABLE cars (
    id                    BIGINT       PRIMARY KEY,
    model                 VARCHAR(80)  NOT NULL,
    body_type             VARCHAR(30)  NOT NULL,
    fuel                  VARCHAR(20)  NOT NULL,
    ex_showroom_price_inr BIGINT       NOT NULL,
    active                BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE bookings (
    id            UUID                     PRIMARY KEY,
    car_id        BIGINT                   NOT NULL REFERENCES cars (id),
    customer_name VARCHAR(80)              NOT NULL,
    phone         VARCHAR(15)              NOT NULL,
    email         VARCHAR(120),
    slot_start    TIMESTAMP                NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT                   NOT NULL
);
CREATE INDEX ix_bookings_car_slot ON bookings (car_id, slot_start);

-- One row per taken slot. The primary key is what stops a double booking, even
-- when two requests race: the second INSERT fails, whatever the app checked before.
-- Cancelling deletes the hold, so the slot can be booked again.
CREATE TABLE slot_holds (
    car_id     BIGINT    NOT NULL REFERENCES cars (id),
    slot_start TIMESTAMP NOT NULL,
    booking_id UUID      NOT NULL UNIQUE REFERENCES bookings (id),
    PRIMARY KEY (car_id, slot_start)
);

-- Transactional outbox: written in the same transaction as the booking,
-- relayed to Kafka afterwards (at-least-once).
CREATE TABLE outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     UUID                     NOT NULL UNIQUE,
    aggregate_id UUID                     NOT NULL,
    event_type   VARCHAR(40)              NOT NULL,
    payload      VARCHAR(4000)            NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts     INT                      NOT NULL DEFAULT 0
);
CREATE INDEX ix_outbox_unpublished ON outbox_events (published_at, id);

-- Written by the event consumer. UNIQUE(event_id) makes the consumer idempotent:
-- a redelivered event cannot create a second notification.
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   UUID                     NOT NULL UNIQUE,
    booking_id UUID                     NOT NULL,
    channel    VARCHAR(20)              NOT NULL,
    message    VARCHAR(400)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_notifications_booking ON notifications (booking_id);
